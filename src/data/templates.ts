/**
 * Resolve a size preset into concrete pixel dimensions.
 * Width is clamped to the allowed custom range so callers can pass raw input.
 */
export function resolveSize(presetId: string, width: number): ArticleSize {
  const safeWidth = Math.min(
    CUSTOM_WIDTH_MAX,
    Math.max(CUSTOM_WIDTH_MIN, Math.round(width) || CUSTOM_WIDTH_MIN)
  );
  const preset = sizePresets.find((p) => p.id === presetId);
  const aspect = preset ? preset.aspect : 1500 / 900;
  return {
    presetId: (preset ? preset.id : 'custom') as ArticleSize['presetId'],
    width: safeWidth,
    height: Math.round(safeWidth * aspect),
  };
}

